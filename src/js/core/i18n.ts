export function t(key: string, ...args: Array<string | number>): string {
  const messages = typeof window !== 'undefined' ? window.MainApp?.messages : undefined;
  const template = (messages && Object.hasOwn(messages, key) ? messages[key] : FALLBACK_MESSAGES[key]) ?? key;
  return template.replace(/\{(\d+)\}/g, (match, index) => (Number(index) < args.length ? String(args[Number(index)]) : match));
}

export function uiLocale(root: { documentElement?: { lang?: string } } | null = typeof document !== 'undefined' ? document : null): string {
  const raw = root?.documentElement?.lang?.trim() || '';
  if (!raw) return 'zh-CN';
  try {
    const [canonical] = Intl.getCanonicalLocales(raw);
    return canonical || 'zh-CN';
  } catch {
    return 'zh-CN';
  }
}
