"""Maintainer-only generator: FontTools 4.60.1 + Brotli 1.1.0; normal builds use checked-in WOFF2."""
import hashlib
import json
import re
from pathlib import Path
import brotli
import fontTools
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
UPSTREAM = ROOT / 'node_modules/@fortawesome/fontawesome-free'
OUTPUT = ROOT / 'src/fonts/fontawesome-subsets'
assert fontTools.__version__ == '4.60.1' and brotli.__version__ == '1.1.0', 'Use pinned fonttools==4.60.1 and brotli==1.1.0'
assert json.loads((UPSTREAM / 'package.json').read_text())['version'] == '6.7.2'
digest = lambda data: hashlib.sha256(data).hexdigest()
metadata = json.loads((UPSTREAM / 'metadata/icon-families.json').read_text())
names, points = set(), set()
for file in sorted([*ROOT.joinpath('src').rglob('*'), ROOT / 'settings.yaml']):
    if not file.is_file() or file.suffix not in ['.html', '.scss', '.ts', '.yaml']:
        continue
    text = file.read_text()
    names.update(re.findall(r'fa-([a-z0-9-]+)', text))
    points.update(int(value, 16) for value in re.findall(r'\\([fFeE][0-9a-fA-F]{3,5})', text))
for name, item in metadata.items():
    if names.intersection([name, *item.get('aliases', {}).get('names', [])]):
        points.add(int(item['unicode'], 16))

OUTPUT.mkdir(parents=True, exist_ok=True)
manifest = {'schema': 1, 'upstreamVersion': '6.7.2', 'tools': {'fonttools': fontTools.__version__, 'brotli': brotli.__version__}, 'inputs': {}, 'fonts': []}
for relative in ['css/all.min.css', 'LICENSE.txt', 'metadata/icon-families.json']:
    manifest['inputs'][relative] = digest((UPSTREAM / relative).read_bytes())
css = ['/* Generated by scripts/fonts/generate-subsets.py; complete upstream fonts remain fallbacks. */']
def unicode_ranges(points):
    ranges = []
    for point in sorted(points):
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ','.join(f'U+{start:X}' + (f'-{end:X}' if start != end else '') for start, end in ranges)

for style, weight in [('solid', 900), ('regular', 400), ('brands', 400)]:
    relative = f'webfonts/fa-{style}-{weight}.woff2'
    source = UPSTREAM / relative
    manifest['inputs'][relative] = digest(source.read_bytes())
    ttf = f'webfonts/fa-{style}-{weight}.ttf'
    manifest['inputs'][ttf] = digest((UPSTREAM / ttf).read_bytes())
    # Keep upstream global bounds as well as per-glyph metrics: Chromium and
    # Firefox use these bounds when positioning an icon-only line box.
    font = TTFont(source, recalcTimestamp=False, recalcBBoxes=False)
    original_points = set(font.getBestCmap())
    chosen = sorted(points.intersection(original_points))
    options = subset.Options()
    options.recalc_timestamp = False
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    options.layout_features = ['*']
    options.hinting = True
    options.harfbuzz_repacker = False
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=chosen)
    subsetter.subset(font)
    family = 'Butterfly Icons Brands' if style == 'brands' else 'Butterfly Icons Free'
    full = 'Butterfly Icons ' + style.title()
    # Rename every identifying name, including legacy/typographic/WWS names.
    # Copyright, OFL license and source attribution records remain untouched.
    for record in font['name'].names:
        values = {1: full, 2: 'Regular', 3: full + ' 6.7.2 subset', 4: full, 6: full.replace(' ', ''), 16: family, 17: style.title(), 18: full, 21: family, 22: style.title()}
        if record.nameID in values:
            record.string = values[record.nameID].encode(record.getEncoding())
    file = f'butterfly-{style}.woff2'
    font.save(OUTPUT / file)
    codes = [f'U+{point:X}' for point in chosen]
    remaining = unicode_ranges(original_points.difference(chosen))
    manifest['fonts'].append({'file': file, 'style': style, 'weight': weight, 'family': family, 'codepoints': codes, 'fallbackUnicodeRange': remaining, 'originalCodepointCount': len(original_points), 'sha256': digest((OUTPUT / file).read_bytes()), 'bytes': (OUTPUT / file).stat().st_size, 'originalBytes': source.stat().st_size})
    # Use one CSS family, not a network-font family stack: some browsers start
    # downloading that fallback while they resolve line metrics. The full font
    # serves every remaining original character, including arbitrary author icons.
    full_sources = f'url("../{relative}") format("woff2"),url("../webfonts/fa-{style}-{weight}.ttf") format("truetype")'
    css.append(f'@font-face{{font-family:"{family}";font-style:normal;font-weight:{weight};font-display:block;src:{full_sources};unicode-range:{remaining}}}')
    # U+20 preserves original line-box font selection. The original fonts contain
    # no space glyph, and we do not invent one; only the CSS coverage includes it.
    # CSS Fonts 4 first available font: https://www.w3.org/TR/css-fonts-4/#font-style-matching
    css.append(f'@font-face{{font-family:"{family}";font-style:normal;font-weight:{weight};font-display:block;src:url("../webfonts/{file}") format("woff2"),{full_sources};unicode-range:U+20,{",".join(codes)}}}')
css.extend([
    ':root{--butterfly-icon-family:"Butterfly Icons Free";--fa-style-family-classic:"Butterfly Icons Free";--fa-style-family-brands:"Butterfly Icons Brands";--fa-font-solid:normal 900 1em/1 "Butterfly Icons Free";--fa-font-regular:normal 400 1em/1 "Butterfly Icons Free";--fa-font-brands:normal 400 1em/1 "Butterfly Icons Brands"}',
    '.fa,.fa-classic,.fa-regular,.fa-solid,.far,.fas{font-family:var(--fa-style-family,"Butterfly Icons Free")}',
    '.fa-brands,.fab{font-family:var(--fa-style-family-brands,"Butterfly Icons Brands")}',
])
data = ('\n'.join(css) + '\n').encode()
(OUTPUT / 'subsets.css').write_bytes(data)
manifest['cssSha256'] = digest(data)
(OUTPUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(json.dumps({row['style']: {'before': row['originalBytes'], 'after': row['bytes'], 'codepoints': len(row['codepoints'])} for row in manifest['fonts']}, indent=2))
